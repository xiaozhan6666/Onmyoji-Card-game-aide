import { test, expect } from '@playwright/test'

test('real catalog, current statistics, search, grade filter and detail navigation', async ({ page }) => {
  const response = await page.request.get('/api/shikigami/3/statistics')
  expect(response.ok()).toBe(true)
  const book = await response.json()
  const exceptions: string[] = []
  page.on('pageerror', e => exceptions.push(e.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '式神观察榜' })).toBeVisible()
  await expect(page.getByRole('row').filter({ hasText: '书翁' })).toContainText(book.win_rate == null ? '基线已建立' : '有统计样本')
  await expect(page.getByRole('row').filter({ hasText: '书翁' })).toContainText(BigInt(book.observed_players).toLocaleString('zh-CN'))
  await page.screenshot({ path: '../data/frontend-checks/overview-desktop.png', fullPage: true })
  await page.getByRole('textbox', { name: '搜索式神' }).fill('不存在的式神')
  await expect(page.getByText('没有符合条件的式神')).toBeVisible()
  await page.getByRole('button', { name: '重置筛选' }).click()
  await page.getByRole('combobox', { name: '段位筛选' }).selectOption('5')
  await page.getByRole('button', { name: '有胜率样本', exact: true }).click()
  await expect(page.getByText('没有符合条件的式神')).toBeVisible()
  await page.getByRole('button', { name: '重置筛选' }).click()
  await page.getByRole('link', { name: '查看书翁详情' }).click()
  await expect(page.getByRole('heading', { name: '分段位表现' })).toBeVisible()
  await expect(page.getByRole('table', { name: '名士与大名士表现' }).getByRole('row')).toHaveCount(3)
  const other = page.locator('details').filter({ has: page.locator('summary', { hasText: '其他段位（五至八段）' }) })
  await expect(other).not.toHaveAttribute('open', '')
  await other.locator('summary').click()
  if (book.grade_statistics.every((g: {grade: number; sample_games: string}) => g.grade >= 9 || g.sample_games === '0')) {
    await expect(other.getByText('保留已采集的真实段位；有有效变化区间后，在这里展示。')).toBeVisible()
  }
  const grandmaster = book.latest_observed_grades.find((g: {grade: number}) => g.grade === 10)
  await expect(page.locator('.distribution-row').filter({ hasText: '大名士' })).toContainText(grandmaster.player_count)
  await expect(page.locator('.games-explanation')).toContainText(`${BigInt(book.sample_games).toLocaleString('zh-CN')} 场`)
  await page.screenshot({ path: '../data/frontend-checks/shuweng-detail.png', fullPage: true })
  await page.getByRole('link', { name: '式神图鉴', exact: true }).click()
  const catalogResponse = await page.request.get('/api/shikigami')
  expect(catalogResponse.ok()).toBe(true)
  const catalog = await catalogResponse.json()
  expect(catalog.length).toBeGreaterThan(0)
  await expect(page.locator('.shikigami-card')).toHaveCount(catalog.length)
  await expect(page.locator('.shikigami-card img').evaluateAll(images => images.every(img => (img as HTMLImageElement).naturalWidth > 0))).resolves.toBe(true)
  expect(exceptions).toEqual([])
})

test('mobile navigation and layout do not overflow the viewport', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '式神观察榜' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  await page.screenshot({ path: '../data/frontend-checks/overview-mobile.png', fullPage: true })
  await page.getByRole('button', { name: '打开导航' }).click()
  await page.getByRole('link', { name: '采集概览', exact: true }).click()
  await expect(page.getByRole('heading', { name: '各式神采集覆盖' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})

test('service failure is explicit and retry recovers without demo data', async ({ page }) => {
  await page.route('**/api/rankings', route => route.fulfill({ status: 503, body: '{}' }))
  await page.goto('/')
  await expect(page.getByRole('alert')).toContainText('暂时无法读取最新数据')
  await expect(page.getByRole('heading', { name: '等待数据服务' })).toBeVisible()
  await page.unroute('**/api/rankings')
  await page.getByRole('button', { name: '重试', exact: true }).click()
  await expect(page.getByRole('heading', { name: '式神观察榜' })).toBeVisible()
  await expect(page.getByRole('alert')).toHaveCount(0)
})

test('other grades keep valid samples accessible without showing empty grade rows', async ({ page }) => {
  const response = await page.request.get('/api/rankings')
  const rows = await response.json()
  const book = rows.find((r: {id: string}) => r.id === '3')
  const grade = book.grade_statistics.find((g: {grade: number}) => g.grade === 5)
  Object.assign(grade, {sample_wins:'1',sample_losses:'1',sample_games:'2',contributing_players:'1',win_rate:'0.500000',status:'INFERRED'})
  await page.route('**/api/rankings', route => route.fulfill({json:rows}))
  await page.setViewportSize({width:390,height:844})
  await page.goto('/#/shikigami/3')
  const other = page.getByRole('table', {name:'其他段位表现'})
  await expect(other).not.toBeVisible()
  await page.locator('summary').filter({hasText:'其他段位（五至八段）'}).click()
  await expect(other).toBeVisible()
  await expect(other.getByRole('row')).toHaveCount(2)
  await expect(other).toContainText('五段')
  await expect(other).toContainText('50.0%')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  await page.screenshot({path:'../data/frontend-checks/other-grades-mobile.png',fullPage:true})
})
